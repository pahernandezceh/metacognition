export const LANGS = ['es', 'en'];

let lang = 'es';

export const getLang = () => lang;

export function setLang(next) {
  lang = LANGS.includes(next) ? next : 'es';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function detectLang(saved, navigatorLangs = []) {
  if (LANGS.includes(saved)) return saved;
  const first = navigatorLangs.find(Boolean) || '';
  return first.toLowerCase().startsWith('es') ? 'es' : 'en';
}

/** Translate `key`, replacing `{var}` placeholders. Arrays are returned as-is. */
export function t(key, vars = {}) {
  const value = STRINGS[lang][key] ?? STRINGS.es[key] ?? key;
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Pluralized lookup for keys that come in `key1` / `keyN` pairs. */
export const tn = (key, n) => t(n === 1 ? `${key}1` : `${key}N`, { n });

export function pct(value) {
  const digits = value > 0 && value < 0.095 ? 1 : 0;
  return new Intl.NumberFormat(lang === 'es' ? 'es-MX' : 'en-US', {
    style: 'percent',
    maximumFractionDigits: digits,
    minimumFractionDigits: digits,
  }).format(value);
}

/** Fills elements marked with data-i18n, data-i18n-placeholder, -title and -aria. */
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
